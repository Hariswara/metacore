"""The pinned M1 -> M4 topology contract (module1.proto GridTopology / GridStateSnapshot).

HAND-WRITTEN accessor. The pin it reads (``schema/module1_topology_v1.json``) and the OpenDSS
model (``topology/northern_islands_v1.dss``) are GENERATED by ``python -m module1.topology build``
from one parameter table, so the network M1 describes and the network M4 solves are the same file.

    from metacore_contracts.topology_schema import DSS_PATH, TOPOLOGY_ID, node_map, sample_snapshot

Status: DRAFT v1.0 for joint M1/M4 sign-off. Not yet M4's default model.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

_HERE = Path(__file__).parent
_PIN = _HERE / "schema" / "module1_topology_v1.json"
_SAMPLES = _HERE / "schema" / "samples"

#: The OpenDSS master file M4's CircuitTwin compiles for this topology.
DSS_PATH: Path = _HERE / "topology" / "northern_islands_v1.dss"


@lru_cache(maxsize=1)
def load() -> dict[str, Any]:
    """The full pin: buses, lines, assets, loads, node map, assumptions, snapshot format."""
    return json.loads(_PIN.read_text())


TOPOLOGY_ID: str = load()["topology_id"]


def node_map() -> dict[str, list[str]]:
    """M1 forecaster node id (e.g. ``Nainativu/bus``) -> topology bus ids it covers."""
    return dict(load()["node_map"])


def bus_ids() -> list[str]:
    return [b["node_id"] for b in load()["buses"]]


def sample_snapshot(name: str) -> dict[str, Any]:
    """A committed GridStateSnapshot fixture: ``calm``, ``nainativu_peak`` or ``ditwah_evening``."""
    return json.loads((_SAMPLES / f"module1_snapshot_v1_{name}.json").read_text())
